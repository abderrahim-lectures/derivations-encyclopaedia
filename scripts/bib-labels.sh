#!/usr/bin/env bash
# Generate the year labels and year groups of the handbook bibliography.
#
#   scripts/bib-labels.sh .   (run from the book directory)
#
# Reads <dir>/bib/*.bib, sorts the entries by year, then by first author
# surname, then by title, and numbers them within each year. Writes, under
# <dir>/build/:
#   bib-labels.tex  biblatex source map giving each entry the label YEAR-n
#                   (field shorthand) and the sort key YEAR-nnnn (field sortkey);
#   bib-years.tex   one \printbibliography per year, under a year heading.
# Entries with no year get the label nd-n and the heading "Undated".
# Runs before every build (latexmkrc, build-chapter.sh); never edits the .bib.
set -euo pipefail
DIR="${1:?usage: bib-labels.sh <handbook dir>}"
mkdir -p "$DIR/build"
python3 - "$DIR" <<'PY'
import re
import sys
import unicodedata
from pathlib import Path

root = Path(sys.argv[1])
ENTRY = re.compile(r'@(\w+)\s*\{\s*([^,\s]+)\s*,(.*?)\n\}', re.S)


def field(body, name):
    m = re.search(r'\b' + name + r'\s*=\s*', body, re.I)
    if not m:
        return ''
    rest = body[m.end():]
    if rest.startswith('{'):
        depth, out = 0, []
        for ch in rest:
            depth += ch == '{'
            depth -= ch == '}'
            out.append(ch)
            if depth == 0:
                break
        return ''.join(out)[1:-1]
    return re.match(r'"?([^",\n]*)', rest).group(1)


def plain(text):
    text = re.sub(r'\\[`\'^"~=.]\{?(\w)\}?', r'\1', text)
    text = re.sub(r'\\[a-zA-Z]+\s*', '', text).replace('{', '').replace('}', '')
    text = unicodedata.normalize('NFKD', text)
    return ''.join(c for c in text if not unicodedata.combining(c)).lower().strip()


entries = []
for bib in sorted((root / 'bib').glob('*.bib')):
    for kind, key, body in ENTRY.findall(bib.read_text(encoding='utf-8')):
        if kind.lower() in ('comment', 'string', 'preamble'):
            continue
        year = re.match(r'\d{4}', field(body, 'year').strip() or field(body, 'date').strip())
        first = field(body, 'author').split(' and ')[0] or field(body, 'editor').split(' and ')[0]
        surname = first.split(',')[0] if ',' in first else (first.split() or [''])[-1]
        entries.append((year.group(0) if year else '', plain(surname), plain(field(body, 'title')), key))

entries.sort(key=lambda e: (e[0] == '', e[0], e[1], e[2], e[3]))
maps, years, count, members = [], [], {}, {}
for year, _, _, key in entries:
    group = year or 'nd'
    count[group] = count.get(group, 0) + 1
    if group not in years:
        years.append(group)
    members.setdefault(group, []).append(key)
    maps.append(
        '  \\map[overwrite]{\\step[fieldsource=entrykey, match=\\regexp{\\A%s\\Z}, final]\n'
        '    \\step[fieldset=shorthand, fieldvalue={%s-%d}]\n'
        '    \\step[fieldset=sortkey, fieldvalue={%s-%04d}]}' % (re.escape(key), group, count[group], group, count[group]))

build = root / 'build'
(build / 'bib-labels.tex').write_text(
    '% Generated by tools/scripts/handbook/bib-labels.sh. Do not edit.\n'
    '\\DeclareSourcemap{\\maps[datatype=bibtex]{\n' + '\n'.join(maps) + '\n}}\n', encoding='utf-8')
cats = ['\n% One bibliography category per year.']
lines = ['% Generated by tools/scripts/handbook/bib-labels.sh. Do not edit.']
for group in years:
    title = 'Undated' if group == 'nd' else group
    cats.append('\\DeclareBibliographyCategory{year%s}' % group)
    cats.append('\\addtocategory{year%s}{%s}' % (group, ','.join(members[group])))
    lines.append('\\printbibliography[heading=subbibliography, title={%s}, category=year%s]' % (title, group))
with open(build / 'bib-labels.tex', 'a', encoding='utf-8') as fh:
    fh.write('\n'.join(cats) + '\n')
(build / 'bib-years.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'bib-labels: {len(entries)} entries in {len(years)} years')
PY
